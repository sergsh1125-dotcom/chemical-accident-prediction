# 3. ДОПОМІЖНІ ФУНКЦІЇ ДЛЯ ІНТЕРПОЛЯЦІЇ ТА ТАБЛИЧНОГО ПОШУКУ
# ==============================================================================

def get_closest_or_interpolated(val: float, available: list) -> float:
    """Знаходить точне або найближче значення в списку табличних точок."""
    available_sorted = sorted(available)
    if val in available_sorted:
        return val
    if val <= available_sorted[0]:
        return available_sorted[0]
    if val >= available_sorted[-1]:
        return available_sorted[-1]
    for i in range(len(available_sorted) - 1):
        if available_sorted[i] <= val <= available_sorted[i+1]:
            # Повертаємо найближчу точний вузол таблиці
            if abs(val - available_sorted[i]) <= abs(val - available_sorted[i+1]):
                return available_sorted[i]
            else:
                return available_sorted[i+1]
    return available_sorted[0]

def calculate_depth_table(table_matrix: dict, table_k: dict, substance: str, atmospheric: str, mass: float, wind_speed: float, temp: float) -> float:
    """
    Чисто табличний розрахунок глибини зараження без використання Q.
    Формула: Г = G_Табл * K_Темп
    """
    if substance not in table_matrix:
        return 0.0
    
    sub_data = table_matrix[substance]
    if atmospheric not in sub_data:
        return 0.0
    
    atm_data = sub_data[atmospheric]
    
    # Вибір найближчих параметрів з таблиці
    avail_masses = list(atm_data.keys())
    closest_mass = get_closest_or_interpolated(mass, avail_masses)
    
    avail_winds = list(atm_data[closest_mass].keys())
    closest_wind = get_closest_or_interpolated(wind_speed, avail_winds)
    
    # 1. Базова глибина з таблиці Додатку
    g_tab = atm_data[closest_mass][closest_wind]
    
    # 2. Поправка на температуру з таблиці коефіцієнтів
    k_tab = 1.0
    if substance in table_k:
        avail_temps = list(table_k[substance].keys())
        closest_temp = get_closest_or_interpolated(temp, avail_temps)
        k_tab = table_k[substance][closest_temp]
        
    return g_tab * k_tab

